// TODO: 2 つの整数の平均を f64 で返してください。
//       average(3, 4) は 3.5 になるはずです (3.0 ではなく！)。
fn average(a: i32, b: i32) -> f64 {
    (a + b) as f64 / 2.0
}

// TODO: 配列の最小値と最大値を、タプル (最小, 最大) で返してください。
fn min_max(values: [i32; 5]) -> (i32, i32) {
    let mut min = values[0];
    let mut max = values[0];
    for v in values {
        if v < min {
            min = v;
        }
        if v > max {
            max = v;
        }
    }
    (min, max)
}

// TODO: タプルの中身を入れ替えて返してください。
//       ヒント: let (n, c) = pair; のように分解（デストラクチャ）できます。
fn swap(pair: (i32, char)) -> (char, i32) {
    let (n, c) = pair;
    (c, n)
}

