// 【解答例】これは一つの書き方です。他の書き方でもテストが通れば正解です！
// ============================================================
// 01: 変数と可変性 (let / mut / シャドーイング / const)
// ============================================================
//
// ■ Rust の変数はデフォルトで「不変 (immutable)」
//
//     let x = 5;
//     x = 6;          // ← コンパイルエラー！ x は書き換えられない
//
//   値を変えたいときは `mut` を付けます。
//
//     let mut y = 5;
//     y = 6;          // OK
//
// ■ シャドーイング
//   同じ名前で `let` し直すと、前の変数を「覆い隠す」新しい変数になります。
//   mut と違い、型を変えることもできます。
//
//     let s = "42";
//     let s: i32 = s.parse().unwrap();   // 文字列 → 数値
//
// ■ 定数
//   const は必ず型を書きます。名前は大文字のスネークケースが慣習です。
//
//     const SECONDS_PER_HOUR: u32 = 60 * 60;
//
// ------------------------------------------------------------
// 課題: コンパイルが通り、テストがすべて成功するように直してください。
//       エラーメッセージをよく読むのがコツです！
// ------------------------------------------------------------

// TODO: このままだとコンパイルエラーになります。なぜでしょう？
fn counter() -> i32 {
    let mut count = 0;
    count += 1;
    count += 1;
    count
}

// TODO: シャドーイングを使って、`text` を「長さ (usize)」に変えてから返してください。
//       ヒント: 文字列の長さは text.len() で取れます。
fn text_length() -> usize {
    let text = "hello";
    let text = text.len();
    text
}

